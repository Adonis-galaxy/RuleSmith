def get_fixed_params() -> Dict[str, float]:
    """
    Get parameters that should NOT be optimized (kept at default values).
    
    Returns:
        Dictionary of fixed parameter names to their values
    """
    default_theta = get_default_theta()
    optimizable = set(get_optimizable_params())
    
    return {
        k: v for k, v in default_theta.items()
        if k not in optimizable
    }


def get_param_precision(param_name: str) -> float:
    """
    Get the discretization precision for a parameter.
    
    Rules:
    - If default value is integer (1, 2, 3) -> precision = 1.0
    - If default value has 1 decimal (1.2, 2.5) -> precision = 0.1
    - If default value has 2 decimals (0.15, 1.25) -> precision = 0.01
    
    Args:
        param_name: Parameter name
        
    Returns:
        Precision value (1.0, 0.1, or 0.01)
    """
    default_theta = get_default_theta()
    if param_name not in default_theta:
        return 1.0
    
    value = default_theta[param_name]
    
    # Check if value is effectively an integer
    if abs(value - round(value)) < 1e-9:
        return 1.0
    
    # Check decimal places
    value_str = f"{value:.10f}".rstrip('0').rstrip('.')
    if '.' in value_str:
        decimal_places = len(value_str.split('.')[1])
        if decimal_places <= 1:
            return 0.1
        else:
            return 0.01
    
    return 1.0


def discretize_theta(theta: Dict[str, float]) -> Dict[str, float]:
    """
    Discretize theta values according to their precision.
    
    Args:
        theta: Continuous parameter values
        
    Returns:
        Discretized parameter values
    """
    discretized = {}
    for param_name, value in theta.items():
        precision = get_param_precision(param_name)
        # Round to nearest multiple of precision
        discretized[param_name] = round(value / precision) * precision
    
    return discretized

