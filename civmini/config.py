def theta_to_array(theta: Dict[str, float]) -> list:
    """Convert theta dict to ordered array for optimization."""
    keys = sorted(theta.keys())
    return [theta[k] for k in keys]


def array_to_theta(arr: list) -> Dict[str, float]:
    """Convert ordered array back to theta dict."""
    default_theta = get_default_theta()
    keys = sorted(default_theta.keys())
    return {k: float(v) for k, v in zip(keys, arr)}


